/**
 * Returns raw SVG markup for a given iconId or customSvg fallback
 */
export function getSvgMarkup(iconId?: string, customSvg?: string): string {
  if (customSvg && customSvg.trim().startsWith('<svg')) {
    return customSvg;
  }
  if (iconId) {
    const found = BUILTIN_SVGS.find((s) => s.id === iconId);
    if (found) return found.svg;
  }
  // Default fallback icon
  return `<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><path d="m19 21-7-4-7 4V5a2 2 0 0 1 2-2h10a2 2 0 0 1 2 2v16z"/></svg>`;
}

/**
 * Intelligent icon detection based on window title or executable / URL
 */
export function detectDefaultIcon(title: string, urlOrExe: string): string {
  const combined = `${title} ${urlOrExe}`.toLowerCase();

  if (combined.includes('youtube')) return 'youtube';
  if (combined.includes('gemini') || combined.includes('chatgpt') || combined.includes('claude')) return 'gemini';
  if (combined.includes('okta') || combined.includes('octa')) return 'okta';
  if (combined.includes('calendar')) return 'calendar';
  if (combined.includes('mail') || combined.includes('gmail') || combined.includes('inbox')) return 'mail';
  if (combined.includes('notion')) return 'notion';
  if (combined.includes('github') || combined.includes('gitlab')) return 'github';
  if (combined.includes('blender')) return 'blender';
  if (combined.includes('calc')) return 'calc';
  if (combined.includes('spotify') || combined.includes('music') || combined.includes('podcast')) return 'music';
  if (combined.includes('slack') || combined.includes('discord') || combined.includes('teams')) return 'slack';
  if (combined.includes('notepad') || combined.includes('.txt') || combined.includes('.md')) return 'file-text';
  if (combined.includes('explorer') || combined.includes('\\') || combined.includes('/')) return 'folder';
  if (combined.includes('powershell') || combined.includes('cmd') || combined.includes('terminal') || combined.includes('bash')) return 'terminal';
  if (combined.includes('code') || combined.includes('.ts') || combined.includes('.rs') || combined.includes('.py')) return 'code';
  if (combined.includes('chrome') || combined.includes('google')) return 'chrome';
  if (combined.includes('http') || combined.includes('.com') || combined.includes('.io') || combined.includes('.app')) return 'globe';

  return 'bookmark';
}
